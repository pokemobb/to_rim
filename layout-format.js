// เขียน layout.json ให้อ่านง่าย: คู่พิกัด [x, z] และ object ที่ไม่มีอะไรซ้อนข้างในอยู่บรรทัดเดียว
// ใช้ทั้งในหน้าเว็บ (ปุ่มดาวน์โหลด) และใน api/ (บันทึกขึ้น GitHub) ให้ไฟล์ออกมาหน้าตาเดียวกัน
export const toJson = (data) => `${JSON.stringify(data, null, 2)
  .replace(/\[\n\s+(-?[\d.]+),\n\s+(-?[\d.]+)\n\s+\]/g, '[$1, $2]')
  .replace(/\{\n\s+([^{}[\]]*?)\n\s+\}/g, (_, body) => `{ ${body.replace(/,\n\s+/g, ', ')} }`)
  .replace(/\{\n\s+("from": \[[^\]]*\]),\n\s+("to": \[[^\]]*\])\n\s+\}/g, '{ $1, $2 }')}\n`;
